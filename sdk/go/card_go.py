"""Generate the Go Card API and its typed ABI verification and output bridge."""

import json
import re
import subprocess
import sys
from tempfile import TemporaryDirectory
import shutil
from pathlib import Path

from tsugumi_ports import load_card_schemas, param_members, write_api_readme


def exported(name):
    result = "".join(part[:1].upper() + part[1:] for part in name.split("_"))
    return result if result and result[0].isalpha() else "Port" + result


def unique(name, used):
    while name in used:
        name += "_"
    used.add(name)
    return name


def members(ports, reserved=()):
    used = set(reserved)
    return [(port, unique(exported(port.name), used)) for port in ports]


class GoTypes:
    def __init__(self, global_package):
        self.global_package = global_package
        self.packages = {}

    def table(self, name):
        namespace, _, leaf = name.rpartition(".")
        package = namespace.replace(".", "/") or self.global_package
        alias = self.packages.setdefault(package, f"port{len(self.packages)}")
        return alias, leaf


def go_type(type_):
    if type_.startswith("["):
        return "[]" + go_type(type_[1:-1])
    return {"bool": "bool", "long": "int64", "double": "float64", "string": "string"}[type_]


def go_literal(value, type_):
    if type_.startswith("["):
        return go_type(type_) + "{" + ", ".join(go_literal(v, type_[1:-1]) for v in value) + "}"
    return json.dumps(value, ensure_ascii=False)


def generate_params(fields, values):
    lines = [
        "// Code generated by the Tsugumi Go SDK. DO NOT EDIT.",
        "package tsugumi",
        "func Parameters() Params {",
        "return Params{",
    ]
    if values is not None:
        lines += [f"{member}: {go_literal(values[param.name], param.type)},"
                  for param, member in fields]
    return "\n".join([*lines, "}", "}", ""])


def parameter_fields(card):
    names = (exported(param.name.replace(".", "_").replace("-", "_")) for param in card.params)
    return list(zip(card.params, param_members(names, ())))


def generate_go(card, inputs, outputs, global_package):
    types = GoTypes(global_package)
    variants = []
    reads = []
    index = 0
    for port, member in inputs:
        input_type = "Input" + member
        field = "input.input" + member
        reads += [
            f"case {json.dumps(port.name)}:",
            f'if {field} != nil {{ return input, fmt.Errorf("duplicate input %q", name) }}',
        ]
        multiple = len(port.candidates) > 1
        if multiple:
            reads += ["switch port.schema {"]
        else:
            schema = port.candidates[0].schema
            reads += [f'if port.hasSchema && port.schema != "{schema}" {{ return input, fmt.Errorf("unknown schema for input %q", name) }}']
        branches = []
        used = set()
        for candidate in port.candidates:
            package, root = types.table(candidate.type)
            expression = f"{package}.GetRootAs{root}(append([]byte(nil), port.bytes...), 0).UnPack()"
            if len(port.candidates) == 1:
                variants.append(f"type {input_type} = {package}.{root}T")
            else:
                branch = unique(exported(root), used)
                branches.append(f"{branch} *{package}.{root}T")
                expression = f"&{input_type}{{{branch}: {expression}}}"
            if multiple:
                reads += [f'case "{candidate.schema}":']
            reads += [
                f'if !verifyInput({index}, port.bytes) {{ return input, fmt.Errorf("invalid FlatBuffer for input %q", name) }}',
                f"{field} = {expression}",
            ]
            index += 1
        if multiple:
            reads += ['default: return input, fmt.Errorf("unknown schema for input %q", name)', "}"]
        if branches:
            variants += [f"type {input_type} struct {{", *branches, "}"]

    writes = []
    for index, (port, member) in enumerate(outputs):
        package, root = types.table(port.type)
        variants += [f"type Output{member} = {package}.{root}T"]
        name = json.dumps(port.name)
        writes += [
            f"if value := output.{member}; value != nil {{",
            f'if !writeOutput(result, {index}, pack(value)) {{ return fmt.Errorf("invalid FlatBuffer for output %q", {name}) }}',
        ]
        if port.required:
            writes += [f'}} else {{ return fmt.Errorf("missing output %q", {name})']
        writes.append("}")

    imports = ['"unsafe"']
    if inputs or outputs:
        imports.append('"fmt"')
    imports += [f'{alias} "tsugumi/{path}"' for path, alias in types.packages.items()]
    lines = [
        "// Code generated by the Tsugumi Go SDK. DO NOT EDIT.",
        "package tsugumi",
        "import (", *imports, ")",
        "type Params struct {",
        *(f"{member} {go_type(param.type)}" for param, member in parameter_fields(card)),
        "}",
        *variants,
        "type Inputs struct {",
        *(f"input{member} *Input{member}" for _, member in inputs),
        "}",
    ]
    for _, member in inputs:
        lines += [
            f"func (input Inputs) {member}() *Input{member} {{",
            f"return input.input{member}",
            "}",
        ]
    lines += [
        "func (input Inputs) value(name string) any {",
        "switch name {",
        *(f"case {json.dumps(port.name)}: if value := input.input{member}; value != nil {{ return value }}"
          for port, member in inputs),
        "}", "return nil", "}",
        "type Output struct {",
        *(f"{member} *Output{member}" for _, member in outputs),
        "}",
        "func readInput(frame inputFrame) (Inputs, error) {",
        "var input Inputs",
    ]
    if inputs:
        lines += [
            "for i := uintptr(0); i < frame.count; i++ {",
            "port, err := frame.port(i)",
            "if err != nil { return input, err }",
            "name := port.name",
            "switch name {",
            *reads,
            'default: return input, fmt.Errorf("unknown input %q", name)',
            "}", "}",
        ]
    else:
        lines += ['if frame.count != 0 { return input, unknownInput() }']
    lines += [f'if input.input{member} == nil {{ return input, &Failure{{Kind: "input_missing", Message: "Missing input " + {json.dumps(port.name)}}} }}'
              for port, member in inputs]
    lines += [
        "return input, nil", "}",
        "func (output Output) send(result unsafe.Pointer) error {",
        *writes, "return nil", "}", "",
    ]
    return "\n".join(lines)


def generate_cpp(inputs, outputs, names, output_schema, cpp):
    input_cases = []
    for index, candidate in enumerate(c for port, _ in inputs for c in port.candidates):
        table = cpp.cpp_type(candidate.type, names)
        input_cases.append(f"    case {index}: return Buffer({{data, size}}).Verify<{table}>() != nullptr;")
    output_cases = []
    roots = [cpp.cpp_type(port.type, names) for port, _ in outputs]
    for index, ((port, _), table) in enumerate(zip(outputs, roots)):
        output_cases.append(f"    case {index}: return WritePort<{table}>(out, {json.dumps(port.name)}, {{data, size}});")

    lines = [
        "// Code generated by the Tsugumi Go SDK. DO NOT EDIT.",
        '#include "host.h"',
        '#include "adapter.hh"',
        '#include "_inputs_generated.h"',
        '#include "_outputs_generated.h"',
        "namespace {",
        "using Tsugumi::Card::CardResultT;",
        "using tsugumi::abi::Buffer;",
        *cpp.validators(output_schema, roots),
    ]
    if outputs:
        lines += [
            "template <class Table>",
            "auto WritePort(void* out, const char* name, tsugumi_bytes bytes) -> bool {",
            "  const Buffer buffer(bytes);",
            "  const auto* table = buffer.Verify<Table>();",
            "  if (!table) return false;",
            "  auto port = std::make_unique<Tsugumi::Card::CardPortT>();",
            "  typename Table::NativeTableType value;",
            "  table->UnPackTo(&value);",
            "  if (!ValidOutput(value)) return false;",
            "  port->name = name;",
            "  port->bytes.assign(bytes.data, bytes.data + bytes.size);",
            "  static_cast<CardResultT*>(out)->outputs.push_back(std::move(port));",
            "  return true;",
            "}",
        ]
    lines += ["}  // namespace"]
    for name, parameters, cases in (
        ("verify_input", "", input_cases),
        ("output", "void* out, ", output_cases),
    ):
        if cases:
            lines += [
                f"auto tsugumi_go_{name}({parameters}size_t index, const uint8_t* data, size_t size) -> int {{",
                "  try {",
                "    switch (index) {",
                *cases,
                "      default: return 0;",
                "    }",
                "  } catch (...) {",
                "    return 0;",
                "  }",
                "}",
            ]
        else:
            types = "void*, " if parameters else ""
            lines += [f"auto tsugumi_go_{name}({types}size_t, const uint8_t*, size_t) -> int {{ return 0; }}"]
    return "\n".join([*lines, ""])


def group_global_types(directory):
    # flatc writes each unnamespaced type as a different package at the
    # output root. Keep the types together so they can reference one another.
    files = sorted(directory.glob("*.go"))
    if not files:
        return None
    package = "schema"
    while (directory / package).exists():
        package += "_"
    (directory / package).mkdir()
    for file in files:
        source = re.sub(r"(?m)^package \w+$", f"package {package}", file.read_text())
        (directory / package / file.name).write_text(source)
        file.unlink()

    names = "|".join(re.escape(file.stem) for file in files)
    pattern = re.compile(rf'^\t(\w+) "(?:{names})"\n', re.M)
    for file in directory.rglob("*.go"):
        source = file.read_text()
        aliases = pattern.findall(source)
        if not aliases:
            continue
        source = pattern.sub("", source)
        alias = "tsugumiSchema"
        while re.search(rf"\b{alias}\b", source):
            alias += "_"
        source = source.replace("import (\n", f'import (\n\t{alias} "tsugumi/{package}"\n', 1)
        for old in aliases:
            source = re.sub(rf"\b{re.escape(old)}\.", f"{alias}.", source)
        file.write_text(source)
    return package


def go_bindings(schemas, directory):
    # flatc's Go backend cannot emit fixed arrays. Private Go codegen lays
    # out the same ArtifactId as sixteen consecutive one-byte fields.
    with TemporaryDirectory() as temp:
        rewritten = Path(temp) / "schemas"
        shutil.copytree(schemas, rewritten, copy_function=shutil.copyfile)
        artifact = rewritten / "tsugumi/artifact.fbs"
        artifact.write_text(artifact.read_text().replace(
            "bytes:[ubyte:16];", " ".join(f"byte_{index}:ubyte;" for index in range(16))))
        for schema in ("_inputs.fbs", "_outputs.fbs", "tsugumi/card.fbs"):
            subprocess.run(["flatc", "--go", "--gen-all", "--gen-object-api",
                            "--go-import", "tsugumi/flatbuffers", "--go-module-name", "tsugumi",
                            "-o", str(directory), "-I", str(rewritten), str(rewritten / schema)],
                           check=True)


def main(schemas, directory, reflection, cpp_directory, cpp_sdk):
    sys.path.insert(0, str(cpp_sdk))
    import card_cpp

    card = load_card_schemas(schemas, reflection)
    inputs = members(card.inputs)
    outputs = members(card.outputs)
    names, output_schema = card_cpp.generate_headers(schemas, cpp_directory, reflection)
    go_bindings(schemas, directory)
    global_package = group_global_types(directory)
    (directory / "card.go").write_text(generate_go(card, inputs, outputs, global_package))
    (directory / "params.go").write_text(generate_params(parameter_fields(card), None))
    (cpp_directory / "card_ports.cc").write_text(
        generate_cpp(inputs, outputs, names, output_schema, card_cpp))
    write_api_readme(
        directory / "README.md",
        ((port.name, f"*Input{member}") for port, member in inputs),
        ((port.name, f"*Output{member}" + (" (required output)" if port.required else ""))
         for port, member in outputs),
        ((param.name, go_type(param.type)) for param in card.params),
    )


if __name__ == "__main__":
    if sys.argv[1] == "embed":
        _, _, schemas, reflection, values, output = sys.argv
        card = load_card_schemas(Path(schemas), Path(reflection))
        Path(output).write_text(generate_params(parameter_fields(card), json.loads(Path(values).read_text())))
    else:
        main(*(Path(path).resolve() for path in sys.argv[1:]))
