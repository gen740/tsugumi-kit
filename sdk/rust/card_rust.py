"""Generate the borrowed input and owned output types for one ABI 9 Card."""

import json
import re
import sys
from pathlib import Path

KEYWORDS = set("""
as async await break const continue crate dyn else enum extern false fn for if impl in let
loop match mod move mut pub ref return self Self static struct super trait true type unsafe
use where while abstract become box do final macro override priv typeof unsized virtual
yield try gen union raw safe
""".split())

# The flatc Rust generator escapes these spellings before converting namespaces.
FLATC_KEYWORDS = (KEYWORDS - set("async await dyn gen raw safe try union".split())) | set("""
alignof offsetof proc pure sizeof std usize isize u8 i8 u16 i16 u32 i32 u64 i64
u128 i128 f32 f64 follow push to_little_endian from_little_endian ENUM_MAX
ENUM_MIN ENUM_VALUES
""".split())

KINDS = {"file": "File", "directory": "Directory", "flatbuffer": "FlatBuffer"}


def snake(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def member(name):
    name = snake(name)
    return name + "_" if name in KEYWORDS or name == "_" else name


def rust_type(name, module):
    *namespace, leaf = (
        part + "_" if part in FLATC_KEYWORDS else part for part in name.split(".")
    )
    # Match flatc's CamelToSnake conversion, including transitions involving digits.
    namespace = [
        re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Z])", "_", part).lower()
        for part in namespace
    ]
    return "::".join([module, *namespace, leaf])


def unique(name, used):
    while name in used:
        name += "_"
    used.add(name)
    return name


def ports(entries, module, reserved=()):
    members = set(reserved)
    aliases = set(KEYWORDS)
    for port in entries:
        name = port["name"]
        field = unique(member(name), members)
        alias = "".join(part[:1].upper() + part[1:] for part in field.split("_"))
        if not alias:
            alias = "Port"
        yield (
            json.dumps(name, ensure_ascii=False),
            field,
            unique(alias, aliases),
            rust_type(port["type"], module),
            f"runtime::PortKind::{KINDS[port['kind']]}",
            port["required"],
        )


def generate(contract):
    inputs = list(ports(contract["inputs"], "input_types", ("params",)))
    outputs = list(ports(contract["outputs"], "output_types"))
    lines = [
        "// Generated by the Tsugumi ABI 9 SDK. Do not edit.",
        "#[allow(warnings)] #[path = \"card_generated.rs\"] mod wire;",
        "#[allow(warnings)] #[path = \"_inputs_generated.rs\"] pub mod input_types;",
        "#[allow(warnings)] #[path = \"_outputs_generated.rs\"] pub mod output_types;",
        "#[allow(warnings)] #[path = \"_params_generated.rs\"] pub mod param_types;",
        "extern crate alloc;",
        "mod runtime;",
        "mod display;",
        "pub extern crate flatbuffers;",
        "pub use display::*;",
        "pub use runtime::{Failure, FailureKind, Result, cancelled, remaining_ms};",
        "#[doc(hidden)] pub use runtime::{Bytes as __Bytes, Effects as __Effects, invoke as __invoke};",
        "",
        "pub type Params<'a> = param_types::parameters::Params<'a>;",
        "pub mod outputs {",
    ]
    for _, _, alias, typ, _, _ in outputs:
        lines.append(f"    pub type {alias} = super::{typ}T;")
    lines += [
        "}",
        "",
        "/// Views borrow the current call. Optional input ports may be absent.",
        "pub struct Inputs<'a> {",
        "    pub params: Params<'a>,",
    ]
    for _, field, _, typ, _, required in inputs:
        typ = f"{typ}<'a>"
        lines.append(f"    pub {field}: {typ if required else f'Option<{typ}>'},")
    lines += [
        "}",
        "",
        "/// Owned output objects. Required ports must contain a value.",
        "#[derive(Default)]",
        "pub struct Output {",
    ]
    for _, field, alias, _, _, required in outputs:
        if required:
            lines.append("    /// Required.")
        lines.append(f"    pub {field}: Option<outputs::{alias}>,")
    lines += [
        "}",
        "",
        "impl<'a> Inputs<'a> {",
        "    #[doc(hidden)]",
        "    pub fn __read(bytes: &'a [u8]) -> Result<Self> {",
        f"        let {'mut ' if inputs else ''}input = runtime::Input::parse(bytes)?;",
        "        Ok(Self {",
    ]
    for name, field, _, typ, kind, required in inputs:
        read = "required" if required else "take"
        lines.append(f"            {field}: input.{read}::<{typ}>({name}, {kind})?,")
    lines += [
        "            params: input.params()?,",
        "        })",
        "    }",
        "}",
        "",
        "impl runtime::PackOutput for Output {",
        "    fn pack(self, builder: &mut flatbuffers::FlatBufferBuilder<'_>) -> Result<()> {",
        f"        let {'mut ' if outputs else ''}ports = Vec::with_capacity({len(outputs)});",
    ]
    for name, field, alias, typ, kind, required in outputs:
        lines += [
            f"        let pack = self.{field}.map(|value: outputs::{alias}| {{",
            "            move |builder: &mut flatbuffers::FlatBufferBuilder<'_>| {",
            "                let root = value.pack(builder);",
            "                builder.finish(root, None);",
            "            }",
            "        });",
            f"        runtime::write_port::<{typ}>(builder, &mut ports,",
            f"            {name}, {kind}, pack, {str(required).lower()})?;",
        ]
    lines += [
        "        runtime::finish_outputs(builder, &ports);",
        "        Ok(())",
        "    }",
        "}",
        "",
        """/// Register a function of type `fn(Inputs<'_>) -> Result<Output>`.
#[macro_export]
macro_rules! export {
    ($run:path) => {
        #[unsafe(no_mangle)]
        unsafe extern "C" fn tsugumi_rust_invoke(
            input: $crate::__Bytes,
            host: *mut ::std::ffi::c_void,
            effects: *const $crate::__Effects,
            result: *mut $crate::__Bytes,
        ) -> ::std::ffi::c_int {
            unsafe {
                $crate::__invoke(input, host, effects, result, |bytes| {
                    let output: $crate::Output = $run($crate::Inputs::__read(bytes)?)?;
                    Ok(output)
                })
            }
        }
    };
}
""",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    contract, output = map(Path, sys.argv[1:])
    output.write_text(generate(json.loads(contract.read_text(encoding="utf-8"))), encoding="utf-8")
