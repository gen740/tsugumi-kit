"""Generate the Go Card face and typed FlatBuffer verification functions."""

import json
import sys
from pathlib import Path

KINDS = {"flatbuffer": "FlatBuffer", "file": "File", "directory": "Directory"}


def exported(name):
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def members(ports, reserved):
    used = set(reserved)
    for port in ports:
        member = exported(port["name"])
        while member in used or not member:
            member += "_"
        used.add(member)
        yield (port, member)


def generate_go(inputs, outputs):
    packages = {}

    def table(port):
        namespace, name = port["type"].rsplit(".", 1)
        package = namespace.replace(".", "/")
        alias = packages.setdefault(package, f"port{len(packages)}")
        return f"{alias}.{name}"

    all_ports = inputs + outputs
    for port, _ in all_ports:
        table(port)

    lines = [
        "// Code generated by the Tsugumi Go SDK. DO NOT EDIT.",
        "package tsugumi",
        "import (",
        '"fmt"',
        '"unsafe"',
        'wire "tsugumi/Tsugumi/Card"',
        '"tsugumi/parameters"',
    ]
    if inputs:
        lines.append('"tsugumi/Tsugumi/Data"')
    if outputs:
        lines.append('"tsugumi/flatbuffers"')
    lines += [f'{alias} "tsugumi/{path}"' for path, alias in packages.items()]
    lines += [")", "type Params = parameters.ParamsT", "type Inputs struct {", "params *Params"]
    lines += [f"input{member} *{table(port)}T" for port, member in inputs]
    lines += ["}", "func (input Inputs) Params() *Params { return input.params }"]
    for port, member in inputs:
        lines += [
            f"func (input Inputs) {member}() *{table(port)}T {{",
            f"return input.input{member}",
            "}",
        ]
    lines += ["type Output struct {"]
    for port, member in outputs:
        lines.append(f"{member} *{table(port)}T")
    lines += ["}"]
    lines += [f"type Output{member} = {table(port)}T" for port, member in outputs]

    lines += [
        "func readInput(frame *wire.CardInput) (Inputs, error) {",
        "var input Inputs",
        "params := frame.ParamsBytes()",
        "if !verifyInput(0, params) { return input, fmt.Errorf(\"invalid params FlatBuffer\") }",
        "input.params = parameters.GetRootAsParams(params, 0).UnPack()",
        "for i := 0; i < frame.InputsLength(); i++ {",
        "var port wire.CardPort",
        "frame.Inputs(&port, i)",
        "name := string(port.Name())",
        "switch name {",
    ]
    for index, (port, member) in enumerate(inputs, 1):
        package, root = table(port).split(".")
        kind = KINDS[port["kind"]]
        lines += [
            f"case {json.dumps(port['name'])}:",
            f'if input.input{member} != nil {{ return input, fmt.Errorf("duplicate input %q", name) }}',
            f'if port.Kind() != Data.PortKind{kind} {{ return input, fmt.Errorf("wrong kind for input %q", name) }}',
            "bytes := port.BytesBytes()",
            f'if !verifyInput({index}, bytes) {{ return input, fmt.Errorf("invalid FlatBuffer for input %q", name) }}',
            f"input.input{member} = {package}.GetRootAs{root}(bytes, 0).UnPack()",
        ]
    lines += ['default: return input, fmt.Errorf("unknown input %q", name)', "}", "}"]
    for port, member in inputs:
        if port["required"]:
            message = json.dumps(f"missing input {port['name']!r}")
            lines.append(f'if input.input{member} == nil {{ return input, &Failure{{Kind: "input_missing", Message: {message}}} }}')
    lines += ["return input, nil", "}", "func (output Output) send(result unsafe.Pointer) error {"]
    for index, (port, member) in enumerate(outputs):
        name = json.dumps(port["name"])
        lines += [
            f"if value := output.{member}; value != nil {{",
            "builder := flatbuffers.NewBuilder(256)",
            "builder.Finish(value.Pack(builder))",
            f'if !writeOutput(result, {index}, builder.FinishedBytes()) {{ return fmt.Errorf("invalid FlatBuffer for output %q", {name}) }}',
        ]
        if port["required"]:
            lines += [f'}} else {{ return fmt.Errorf("missing output %q", {name})']
        lines.append("}")
    lines += ["return nil", "}", ""]
    return "\n".join(lines)


def generate_cpp(inputs, outputs):
    def cpp_type(port):
        return "::" + port["type"].replace(".", "::")

    lines = [
        "// Code generated by the Tsugumi Go SDK. DO NOT EDIT.",
        '#include "host.h"',
        '#include "adapter.hh"',
        '#include "_inputs_generated.h"',
        '#include "_outputs_generated.h"',
        '#include "_params_generated.h"',
        "",
        "namespace {",
        "using Tsugumi::Card::CardPortT;",
        "using Tsugumi::Card::CardResultT;",
        "using tsugumi::abi9::Buffer;",
        "using tsugumi::abi9::PortKind;",
        "",
        "template <class Table>",
        "auto WritePort(CardResultT& result, const char* name, PortKind kind,",
        "               tsugumi_bytes bytes) -> bool {",
        "  if (!Buffer(bytes).Verify<Table>()) return false;",
        "  auto port = std::make_unique<CardPortT>();",
        "  port->name = name;",
        "  port->kind = kind;",
        "  port->bytes.assign(bytes.data, bytes.data + bytes.size);",
        "  result.outputs.push_back(std::move(port));",
        "  return true;",
        "}",
        "}  // namespace",
        "",
        "auto tsugumi_go_verify_input(size_t index, const uint8_t* data, size_t size) -> int {",
        "  try {",
        "    const Buffer buffer({data, size});",
        "    switch (index) {",
        "      case 0: return buffer.Verify<::parameters::Params>() != nullptr;",
    ]
    for index, (port, _) in enumerate(inputs, 1):
        lines += [f"      case {index}: return buffer.Verify<{cpp_type(port)}>() != nullptr;"]
    lines += [
        "      default: return 0;",
        "    }",
        "  } catch (...) {",
        "    return 0;",
        "  }",
        "}",
        "",
        "auto tsugumi_go_output(void* raw, size_t index, const uint8_t* data, size_t size) -> int {",
    ]
    if outputs:
        lines += [
            "  auto& result = *static_cast<CardResultT*>(raw);",
            "  try {",
            "    switch (index) {",
        ]
        for index, (port, _) in enumerate(outputs):
            name = json.dumps(port["name"])
            kind = KINDS[port["kind"]]
            lines += [
                f"      case {index}: return WritePort<{cpp_type(port)}>(",
                f"          result, {name}, PortKind::{kind}, {{data, size}});",
            ]
        lines += [
            "      default: return 0;",
            "    }",
            "  } catch (...) {",
            "    return 0;",
            "  }",
        ]
    else:
        lines[-1] = "auto tsugumi_go_output(void*, size_t, const uint8_t*, size_t) -> int {"
        lines += ["  return 0;"]
    lines += ["}", ""]
    return "\n".join(lines)


def main(contract, directory):
    inputs = list(members(contract["inputs"], {"Params"}))
    outputs = list(members(contract["outputs"], set()))
    (directory / "card.go").write_text(generate_go(inputs, outputs))
    (directory / "card_ports.cc").write_text(generate_cpp(inputs, outputs))


if __name__ == "__main__":
    main(json.loads(Path(sys.argv[1]).read_text()), Path(sys.argv[2]))
