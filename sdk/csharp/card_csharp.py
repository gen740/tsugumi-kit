"""Generate ABI 9 input and output types from the resolved Card contract."""

import json
import re
import sys
from pathlib import Path


KINDS = {"file": "File", "directory": "Directory", "flatbuffer": "FlatBuffer"}


def csharp_type(name):
    return "global::" + ".".join("@" + part for part in name.split("."))


def ports(entries, reserved):
    used = set(reserved)
    for port in entries:
        name = port["name"]
        prop = name[:1].upper() + name[1:]
        while prop in used:
            prop += "_"
        used.add(prop)
        yield json.dumps(name), "@" + prop, csharp_type(port["type"]), KINDS[port["kind"]], port["required"]


def fix_pack_collisions(sources):
    """Keep flatc's Pack method unless a generated type or member already uses that name."""
    renamed = {}
    for path, text in sources.items():
        method = re.search(r"^  public static Offset<([\w.]+)> (Pack)\(", text, re.M)
        if not method:
            continue
        type_name = method[1]
        short_name = type_name.rsplit(".", 1)[-1]
        # Before the static Pack method, flatc emits the raw type's accessors.
        members = set(re.findall(r"^  public (?:static )?\S+ (\w+)[ (]", text[:method.start()], re.M))
        if short_name != "Pack" and "Pack" not in members:
            continue
        pack_name = "Pack_"
        while pack_name in members:
            pack_name += "_"
        renamed[type_name] = pack_name
        text = text[:method.start(2)] + pack_name + text[method.end(2):]
        # SerializeToBinary calls the method without its namespace in this file.
        text = re.sub(rf"(?<![\w.]){re.escape(short_name)}\.Pack\(fbb, this\)",
                      f"{short_name}.{pack_name}(fbb, this)", text)
        sources[path] = text

    if renamed:
        names = "|".join(re.escape(name) for name in renamed)
        calls = re.compile(rf"(?<![\w.])({names})\.Pack\(")
        for path, text in sources.items():
            sources[path] = calls.sub(lambda match: f"{match[1]}.{renamed[match[1]]}(", text)
    return {csharp_type(name): method for name, method in renamed.items()}


def generate(contract, pack_methods):
    inputs = list(ports(contract["inputs"], {"Input", "Params"}))
    outputs = list(ports(contract["outputs"], {"Output", "ToWire", "Pack"}))
    lines = [
        "// Generated by the Tsugumi ABI 9 SDK. Do not edit.",
        "#nullable enable",
        "using System;",
        "using System.Collections.Generic;",
        "using Google.FlatBuffers;",
        "using Tsugumi.Data;",
        "using Wire = Tsugumi.Card;",
        "namespace Tsugumi;",
        "",
        "public sealed class Input",
        "{",
        "    public global::parameters.ParamsT Params { get; }",
    ]
    for _, prop, type_name, _, required in inputs:
        lines.append(f"    public {type_name}T{'' if required else '?'} {prop} {{ get; }}")
    lines += [
        "",
        "    internal Input(InputPorts ports)",
        "    {",
        '        var parameters = InputPorts.Verify(ports.Params, global::parameters.ParamsVerify.Verify, "params", FailureKind.invalid_request);',
        "        Params = global::parameters.Params.GetRootAsParams(parameters).UnPack();",
    ]
    for index, (name, prop, type_name, kind, required) in enumerate(inputs):
        root = type_name.rsplit(".@", 1)[-1]
        flag = str(required).lower()
        lines.append(f"        var bytes{index} = ports.Take({name}, PortKind.{kind}, {flag});")
        if not required:
            lines += [f"        if (bytes{index} is not null)", "        {"]
        indent = "        " if required else "            "
        lines += [
            f"{indent}var buffer{index} = InputPorts.Verify(bytes{index}, {type_name}Verify.Verify, {name}, FailureKind.invalid_request);",
            f"{indent}{prop} = {type_name}.GetRootAs{root}(buffer{index}).UnPack();",
        ]
        if not required:
            lines.append("        }")
    lines += ["    }", "}", "", "public sealed class Output", "{"]
    for _, prop, type_name, _, required in outputs:
        modifier = "required " if required else ""
        suffix = "" if required else "?"
        lines.append(f"    public {modifier}{type_name}T{suffix} {prop} {{ get; set; }}")
    lines += [
        "",
        "    internal Wire.CardResultT ToWire()",
        "    {",
        "        var result = new Wire.CardResultT { Outputs = new List<Wire.CardPortT>() };",
    ]
    for index, (name, prop, type_name, kind, required) in enumerate(outputs):
        pack_method = pack_methods.get(type_name, "Pack")
        if required:
            lines += [
                f"        if ({prop} is null)",
                f'            throw InputPorts.Rejected(FailureKind.output_invalid, "Missing output " + {name});',
            ]
        lines += [
            f"        if ({prop} is {{ }} value{index})",
            "        {",
            f"            var bytes = Pack({name}, {type_name}Verify.Verify, builder => {type_name}.{pack_method}(builder, value{index}).Value);",
            f"            result.Outputs.Add(new() {{ Name = {name}, Kind = PortKind.{kind}, Bytes = new List<byte>(bytes) }});",
            "        }",
        ]
    lines += ["        return result;", "    }"]
    if outputs:
        lines += [
            "",
            "    private static byte[] Pack(string name, VerifyTableAction verify, Func<FlatBufferBuilder, int> pack)",
            "    {",
            "        byte[] bytes;",
            "        try",
            "        {",
            "            var builder = new FlatBufferBuilder(256);",
            "            builder.Finish(pack(builder));",
            "            bytes = builder.SizedByteArray();",
            "        }",
            "        catch (Exception error)",
            "        {",
            '            throw InputPorts.Rejected(FailureKind.output_invalid, $"Invalid output {name}: {error.Message}");',
            "        }",
            "        InputPorts.Verify(bytes, verify, name, FailureKind.output_invalid);",
            "        return bytes;",
            "    }",
        ]
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    output = Path(sys.argv[2])
    sources = {source: source.read_text() for source in output.parent.rglob("*.cs")}
    pack_methods = fix_pack_collisions(sources)
    # flatc emits namespace references both qualified and unqualified. The
    # segments of generated port namespaces may be C# keywords (e.g. "out").
    for generated, text in sources.items():
        text = re.sub(
            r'("(?:[^"\\]|\\.)*"|//[^\n]*)|\b(inputs|outputs|parameters)(?:\.[A-Za-z_]\w*)*',
            lambda match: match[0] if match[1] else ".".join("@" + part for part in match[0].split(".")),
            text,
        )
        # flatc's verifier accepts unknown union discriminators by default.
        # Preserve NONE while rejecting unknown tags at the input/output boundary.
        text = re.sub(
            r"(switch\(\(([A-Za-z_]\w*)\)typeId\)[\s\S]*?)default: result = true;",
            r"\1case \2.NONE: result = true; break;\n      default: result = false;",
            text,
        )
        generated.write_text(text)
    output.write_text(generate(json.loads(Path(sys.argv[1]).read_text()), pack_methods))
